window.HANKKI_PACK_PRICE = (k, i) => { const p = window.HANKKI_PACKS[i]; return i === 0 ? k.price : Math.round(k.price * p.n * p.f / 500) * 500; };
window.HANKKI_CART = {
  get() { try { return JSON.parse(localStorage.getItem('hankki-cart')) || []; } catch (e) { return []; } },
  set(c) { localStorage.setItem('hankki-cart', JSON.stringify(c)); window.dispatchEvent(new Event('hankki-cart')); },
  add(kitId, pack, qty) { const c = this.get(); const f = c.find(x => x.kitId === kitId && x.pack === pack); if (f) f.qty = Math.min(99, f.qty + qty); else c.push({ kitId, pack, qty }); this.set(c); },
  count() { return this.get().reduce((s, x) => s + x.qty, 0); }
};
